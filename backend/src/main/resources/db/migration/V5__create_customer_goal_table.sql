
-- Stores private fitness goals for customers assigned to a trainer.
-- Each goal belongs to a trainer_customer assignment, not directly
-- to a university customer. This keeps different trainers' goals separate.

CREATE TABLE customer_goal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Links the goal to an assignment in our PostgreSQL database.
    trainer_customer_id BIGINT NOT NULL,

    -- A short, descriptive name for the fitness goal.
    title VARCHAR(255) NOT NULL,

    -- Optional additional details about the goal.
    description TEXT,

    -- Optional deadline for achieving the goal.
    target_date DATE,

    -- Tracks the goal's current progress state.
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    -- Optional number of training sessions needed to complete the goal.
    target_sessions INTEGER,

    -- Record when the goal was created and last modified.
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    -- Prevent goals from belonging to nonexistent assignments.
    CONSTRAINT fk_customer_goal_trainer_customer
        FOREIGN KEY (trainer_customer_id)
        REFERENCES trainer_customer(id)
        ON DELETE CASCADE,

    -- Only supported goal statuses are accepted.
    CONSTRAINT chk_customer_goal_status
        CHECK (status IN ('ACTIVE', 'COMPLETED', 'CANCELLED')),

    -- A session target, when provided, must be greater than zero.
    CONSTRAINT chk_customer_goal_target_sessions
        CHECK (target_sessions IS NULL OR target_sessions > 0)
);

-- Speeds up loading the goals for a particular assigned customer.
CREATE INDEX idx_customer_goal_trainer_customer_id
    ON customer_goal(trainer_customer_id);
