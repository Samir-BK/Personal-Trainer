-- Links trainers in our database to customers from the university REST API.
-- Different trainers may assign the same university customer.

CREATE TABLE trainer_customer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- References an authenticated trainer in our PostgreSQL database.
    trainer_id BIGINT NOT NULL,

    -- Stores the customer ID from the university REST API.
    -- No foreign key is possible because that database is external.
    university_customer_id BIGINT NOT NULL,

    -- Records when the customer was assigned to the trainer.
    assigned_at TIMESTAMP WITH TIME ZONE NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    -- Prevent assignments to trainers that do not exist.
    CONSTRAINT fk_trainer_customer_trainer
        FOREIGN KEY (trainer_id)
        REFERENCES trainer(id),

    -- A trainer cannot assign the same customer more than once.
    -- Multiple trainers may still assign the same customer.
    CONSTRAINT uq_trainer_customer
        UNIQUE (trainer_id, university_customer_id)
);

-- Helps retrieve all customers assigned to a specific trainer.
CREATE INDEX idx_trainer_customer_trainer_id
    ON trainer_customer(trainer_id);